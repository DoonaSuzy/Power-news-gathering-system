/** 数字 + 单位，用来判定「含量化数据」。 */
export const QUANTITY_RE =
  /[±+\-]?\d+(?:\.\d+)?\s*(?:亿|万|千|百)?\s*(?:千瓦时|千瓦|千伏安|千伏|兆瓦|吉瓦|kWh|MWh|GWh|GW|MW|kW|kV|kVA|吨|万吨|%|％|个百分点|亿元|万元|元|台|座|个|项|家|条|公里|千米)/

/**
 * 在文本里找出命中的维度词。
 *
 * 返回 ``{维度: [词...]}``，顺序按词表顺序固定 —— 保证同样文本两次调用得到
 * 同样的标签序（UI 不会每次刷新都换顺序）。
 */
export function matchDimensions(text) {
  const haystack = String(text || '')
  const topics = TOPIC_TERMS.filter((t) => haystack.includes(t))
  const actors = ACTOR_TERMS.filter((t) => haystack.includes(t))
  const attributes = Object.entries(ATTRIBUTE_TERMS)
    .filter(([, words]) => words.some((w) => haystack.includes(w)))
    .map(([name]) => name)
  return { 主题: topics, 主体: actors, 属性: attributes }
}

/** 该文本是否含量化数据。 */
export function hasQuantity(text) {
  return QUANTITY_RE.test(String(text || ''))
}
